# =========================================================
# SUBPROCESS
# =========================================================

def _run(
    cmd,
    *,
    input=None,
    text=False,
    timeout=None,
    **kwargs,
):
    """
    Run external commands safely.

    IMPORTANT:
    When text=True, always use UTF-8 explicitly.

    Windows otherwise defaults to the system code page,
    commonly cp1252, which cannot encode many Unicode
    characters generated by modern LLMs.
    """

    run_kwargs = {
        "stdout": subprocess.PIPE,
        "stderr": subprocess.PIPE,
        "check": False,
    }

    run_kwargs.update(
        kwargs
    )

    if input is not None:
        run_kwargs["input"] = input

    if timeout is not None:
        run_kwargs["timeout"] = timeout

    if text:
        run_kwargs["text"] = True

        # =================================================
        # THIS IS THE FIX FOR YOUR CURRENT ERROR
        # =================================================

        run_kwargs["encoding"] = "utf-8"

        run_kwargs["errors"] = "replace"

    completed = subprocess.run(
        cmd,
        **run_kwargs,
    )

    if completed.returncode != 0:

        stderr = completed.stderr

        if isinstance(
            stderr,
            bytes,
        ):
            stderr = stderr.decode(
                "utf-8",
                errors="replace",
            )

        stdout = completed.stdout

        if isinstance(
            stdout,
            bytes,
        ):
            stdout = stdout.decode(
                "utf-8",
                errors="replace",
            )

        raise RuntimeError(
            "\n".join(
                [
                    (
                        f"Command failed "
                        f"({completed.returncode})"
                    ),
                    "",
                    "Command:",
                    " ".join(
                        map(
                            str,
                            cmd,
                        )
                    ),
                    "",
                    "STDERR:",
                    str(stderr or ""),
                    "",
                    "STDOUT:",
                    str(stdout or ""),
                ]
            )
        )

    return completed


# =========================================================
# SPEECH TEXT NORMALIZATION
# =========================================================

def sanitize_unicode_text(text: str) -> str:
    """Replace invalid isolated UTF-16 surrogates with spaces."""
    text = str(text or "")
    text = re.sub(r"[\ud800-\udfff]+", " ", text)

    # This strict round trip is an invariant for every TTS backend.
    # It also protects subprocess stdin and temporary UTF-8 text files.
    return text.encode("utf-8", errors="strict").decode("utf-8")

def normalize_tts_text(
    text: str,
) -> str:
    """
    Convert arbitrary LLM narration into TTS-friendly
    Unicode text.

    This is deliberately GENERIC.

    It is not tied to binary search or any particular
    educational subject.

    We preserve language/content while converting common
    visual symbols into forms that speech engines handle
    more naturally.
    """

    text = sanitize_unicode_text(text)

    # Normalize equivalent Unicode representations.
    text = unicodedata.normalize(
        "NFKC",
        text,
    )

    # =====================================================
    # SYMBOLS THAT SHOULD BE SPOKEN
    # =====================================================

    replacements = {
        # Arrows
        "→": " leads to ",
        "⇒": " implies ",
        "⟶": " leads to ",
        "➜": " leads to ",
        "➝": " leads to ",

        "←": " comes from ",
        "⇐": " is implied by ",
        "⟵": " comes from ",

        "↔": " corresponds to ",
        "⇔": " if and only if ",

        # Comparisons
        "≥": " greater than or equal to ",
        "≤": " less than or equal to ",
        "≠": " not equal to ",
        "≈": " approximately ",
        "≃": " approximately ",
        "≅": " approximately equal to ",

        # Arithmetic
        "×": " times ",
        "÷": " divided by ",
        "−": " minus ",

        # Typography
        "—": ", ",
        "–": ", ",
        "…": "...",

        "“": '"',
        "”": '"',
        "‘": "'",
        "’": "'",

        # Misc common technical symbols
        "∞": " infinity ",
        "°": " degrees ",
        "±": " plus or minus ",
    }

    for source, target in (
        replacements.items()
    ):
        text = text.replace(
            source,
            target,
        )

    # =====================================================
    # REMOVE CHARACTERS THAT ARE COMMONLY VISUAL MARKUP
    # RATHER THAN SOMETHING A VOICE SHOULD PRONOUNCE
    # =====================================================

    # Markdown bold/italic markers.
    text = text.replace(
        "**",
        "",
    )

    # Markdown headings.
    text = re.sub(
        r"(?m)^\s*#{1,6}\s*",
        "",
        text,
    )

    # Markdown bullets become natural sentence boundaries.
    text = re.sub(
        r"(?m)^\s*[-*•]\s+",
        "",
        text,
    )

    # =====================================================
    # WHITESPACE NORMALIZATION
    # =====================================================

    text = re.sub(
        r"[ \t]+",
        " ",
        text,
    )

    text = re.sub(
        r"\n{3,}",
        "\n\n",
        text,
    )

    text = text.strip()

    return text


# =========================================================
# BACKEND DETECTION
# =========================================================

def resolve_backend() -> str:

    if TTS_BACKEND not in {
        "auto",
        "piper",
        "espeak",
    }:
        raise ValueError(
            "TTS_BACKEND must be "
            "auto, piper, or espeak."
        )

    piper_executable = (
        shutil.which(
            PIPER_BIN
        )
    )

    piper_model_exists = (
        bool(PIPER_MODEL)
        and Path(
            PIPER_MODEL
        ).exists()
    )

    piper_ok = bool(
        piper_executable
        and piper_model_exists
    )

    espeak_ok = bool(
        shutil.which(
            ESPEAK_BIN
        )
    )

    # -----------------------------------------------------
    # Explicit Piper
    # -----------------------------------------------------

    if TTS_BACKEND == "piper":

        if not piper_ok:
            raise RuntimeError(
                "Piper selected but Piper executable "
                "or PIPER_MODEL is unavailable.\n"
                f"PIPER_BIN={PIPER_BIN!r}\n"
                f"PIPER_MODEL={PIPER_MODEL!r}"
            )

        return "piper"

    # -----------------------------------------------------
    # Explicit eSpeak
    # -----------------------------------------------------

    if TTS_BACKEND == "espeak":

        if not espeak_ok:
            raise RuntimeError(
                "eSpeak selected but executable "
                "was not found."
            )

        return "espeak"

    # -----------------------------------------------------
    # Automatic selection
    # -----------------------------------------------------

    if piper_ok:
        return "piper"

    if espeak_ok:
        return "espeak"

    raise RuntimeError(
        "No local TTS backend found. "
        "Install/configure Piper or eSpeak."
    )


# =========================================================
# SYNTHESIS
# =========================================================

def synthesize(
    text: str,
    output_wav: Path,
    voice: Optional[str] = None,
    job_id: Optional[str] = None,
) -> Path:

    # =====================================================
    # Normalize BEFORE handing narration to any local
    # speech engine.
    # =====================================================

    original_text = str(
        text or ""
    ).strip()

    if not original_text:
        raise ValueError(
            "Cannot synthesize empty narration."
        )

    speech_text = normalize_tts_text(
        original_text
    )

    if not speech_text:
        raise ValueError(
            "Narration became empty after "
            "TTS normalization."
        )

    output_wav = Path(
        output_wav
    )

    output_wav.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    backend = resolve_backend()

    print(
        f"TTS backend: {backend}"
    )

    import time as _tts_time

    _tts_started = _tts_time.perf_counter()

    # =====================================================
    # PIPER
    # =====================================================

    if backend == "piper":

        cmd = [
            PIPER_BIN,

            "--model",
            PIPER_MODEL,

            "--output_file",
            str(
                output_wav
            ),

            "--length-scale",
            f"{PIPER_LENGTH_SCALE:.3f}",
        ]

        # Send bytes instead of relying on Windows text-mode pipes. Force
        # Piper's Python process to decode redirected stdin as strict UTF-8.
        piper_env = os.environ.copy()
        piper_env["PYTHONIOENCODING"] = "utf-8:strict"
        piper_env["PYTHONUTF8"] = "1"
        speech_bytes = (speech_text + "\n").encode(
            "utf-8",
            errors="strict",
        )

        _tts_status = "ok"
        _tts_error = None
        try:
            _run(
                cmd,
                input=speech_bytes,
                env=piper_env,
            )
        except Exception as exc:
            # Piper may create a headerless/empty WAV before failing.
            output_wav.unlink(missing_ok=True)
            _tts_status = "error"
            _tts_error = str(exc)[:300]
            raise
        finally:
            if job_id:
                try:
                    from run_log import log_tts_call

                    log_tts_call(
                        job_id=job_id,
                        engine="piper",
                        fallback_used=False,
                        latency_ms=(_tts_time.perf_counter() - _tts_started) * 1000,
                        status=_tts_status,
                        error=_tts_error,
                    )
                except Exception:  # noqa: BLE001 — logging never breaks TTS
                    pass

        if not output_wav.exists():
            raise RuntimeError(
                "Piper finished without creating "
                f"{output_wav}"
            )

        if (
            output_wav.stat().st_size
            <= 44
        ):
            raise RuntimeError(
                "Piper produced an empty or invalid "
                f"WAV file: {output_wav}"
            )

        return output_wav

    # =====================================================
    # ESPEAK FALLBACK
    #
    # File input is explicitly UTF-8.
    # =====================================================

    text_file = (
        output_wav
        .with_suffix(
            ".txt"
        )
    )

    text_file.write_text(
        speech_text,
        encoding="utf-8",
    )

    try:

        cmd = [
            ESPEAK_BIN,

            "-f",
            str(
                text_file
            ),

            "-w",
            str(
                output_wav
            ),

            "-s",
            str(
                TTS_SPEED_WPM
            ),

            "-v",
            voice or TTS_VOICE,
        ]

        _run(
            cmd
        )

        if job_id:
            try:
                from run_log import log_tts_call

                log_tts_call(
                    job_id=job_id,
                    engine="espeak",
                    fallback_used=True,
                    latency_ms=(_tts_time.perf_counter() - _tts_started) * 1000,
                    status="ok",
                )
            except Exception:  # noqa: BLE001
                pass

    finally:
        text_file.unlink(
            missing_ok=True
        )

    return output_wav


# =========================================================
# AUDIO DURATION
# =========================================================

def audio_duration_seconds(
    path: Path,
) -> float:

    path = Path(
        path
    )

    cmd = [
        FFPROBE_BIN,

        "-v",
        "error",

        "-show_entries",
        "format=duration",

        "-of",
        "default=noprint_wrappers=1:nokey=1",

        str(
            path
        ),
    ]

    result = _run(
        cmd
    )

    raw = result.stdout

    if isinstance(
        raw,
        bytes,
    ):
        raw = raw.decode(
            "utf-8",
            errors="replace",
        )

    raw = str(
        raw
    ).strip()

    if not raw:
        raise RuntimeError(
            f"ffprobe returned no duration "
            f"for {path}"
        )

    return float(
        raw
    )


def pad_wav_to_duration(input_wav: Path, output_wav: Path, target_seconds: float) -> Dict[str, float]:
    """Copy a WAV and append silence up to ``target_seconds``.

    Speech samples are never resampled, stretched, or overwritten. The result
    therefore preserves the natural voice and adds only a scene-boundary hold.
    If raw speech is already longer than its target it is copied unchanged.
    """
    input_wav, output_wav = Path(input_wav), Path(output_wav)
    output_wav.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(input_wav), "rb") as source:
        params = source.getparams()
        frames = source.readframes(source.getnframes())
        raw_frames = source.getnframes()
        frame_rate = source.getframerate()
    raw_seconds = raw_frames / max(1, frame_rate)
    requested_pause = max(0.0, float(target_seconds) - raw_seconds)
    silence_frames = max(0, round(requested_pause * frame_rate))
    with wave.open(str(output_wav), "wb") as destination:
        destination.setparams(params)
        destination.writeframes(frames)
        if silence_frames:
            destination.writeframes(b"\x00" * silence_frames * params.nchannels * params.sampwidth)
    final_seconds = (raw_frames + silence_frames) / max(1, frame_rate)
    return {
        "raw_duration_seconds": round(raw_seconds, 6),
        "boundary_pause_seconds": round(silence_frames / max(1, frame_rate), 6),
        "final_duration_seconds": round(final_seconds, 6),
        "overshoot_seconds": round(max(0.0, raw_seconds - float(target_seconds)), 6),
    }


# =========================================================
# TEMPO ADJUSTMENT
# =========================================================

def adjust_tempo(
    input_wav: Path,
    output_wav: Path,
    tempo: float,
) -> Path:
    """
    Change speech tempo without changing pitch.

    Approximate relationship:

        output duration
        =
        input duration / tempo
    """

    tempo = float(
        tempo
    )

    if tempo <= 0:
        raise ValueError(
            "tempo must be positive"
        )

    input_wav = Path(
        input_wav
    )

    output_wav = Path(
        output_wav
    )

    output_wav.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    # =====================================================
    # FFmpeg atempo chaining
    # =====================================================

    filters = []

    remaining = tempo

    while remaining > 2.0:

        filters.append(
            "atempo=2.0"
        )

        remaining /= 2.0

    while remaining < 0.5:

        filters.append(
            "atempo=0.5"
        )

        remaining /= 0.5

    filters.append(
        f"atempo={remaining:.8f}"
    )

    cmd = [
        FFMPEG_BIN,
        "-y",

        "-i",
        str(
            input_wav
        ),

        "-filter:a",
        ",".join(
            filters
        ),

        "-ar",
        "48000",

        "-ac",
        "1",

        str(
            output_wav
        ),
    ]

    _run(
        cmd
    )

    return output_wav


