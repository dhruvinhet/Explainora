def _extract_transcription_words(resp: Any) -> List[Dict[str, Any]]:
    """Normalize Groq/OpenAI verbose transcription word payloads.

    Providers may return word timestamps either as a top-level ``words`` list
    or nested under ``segments[*].words``. The former was previously ignored,
    causing successful calls to save no words.json file.
    """
    raw_words = getattr(resp, "words", None)
    if raw_words is None and isinstance(resp, dict):
        raw_words = resp.get("words")
    if not raw_words:
        raw_words = []
        segments = getattr(resp, "segments", None)
        if segments is None and isinstance(resp, dict):
            segments = resp.get("segments")
        for seg in segments or []:
            nested = getattr(seg, "words", None)
            if nested is None and isinstance(seg, dict):
                nested = seg.get("words")
            raw_words.extend(nested or [])

    words: List[Dict[str, Any]] = []
    for word in raw_words:
        if isinstance(word, dict):
            word_text = word.get("word", "") or ""
            start = word.get("start", 0)
            end = word.get("end", 0)
        else:
            word_text = getattr(word, "word", "") or ""
            start = getattr(word, "start", 0)
            end = getattr(word, "end", 0)
        word_text = re.sub(r"\s+", " ", str(word_text)).strip()
        if not word_text:
            continue
        words.append({
            "word": word_text,
            "start": round(float(start or 0), 3),
            "end": round(float(end or 0), 3),
        })
    return words

def word_timestamps(
    wav_path: Path,
    job_id: Optional[str] = None,
    max_attempts: int = 3,
) -> Optional[List[Dict[str, Any]]]:
    """Return word-level timestamps for a narration WAV via Groq Whisper.

    Returns a list of dicts [{word, start, end}, ...] in audio seconds, or
    None on failure (whisper timestamps are best-effort — the pipeline keeps
    working with narration-relative timing if this fails).
    """
    wav_path = Path(wav_path).resolve()
    if not wav_path.is_file():
        return None

    try:
        from api_key_pool import groq_pool
        from openai import OpenAI
        from llm_provider import _DEFAULT_BASE_URLS
    except ImportError:
        return None

    # Share the real pool across scenes. Creating a fresh pool per scene made
    # all concurrent Whisper requests pick the same first key and discarded
    # quarantine/load information immediately afterward.
    pool = groq_pool()
    entries = pool.entries()
    if not entries:
        return None

    last_error = None
    # Whisper calls are small audio files, not token-heavy; estimate a cheap
    # ledger weight so the pool still spreads the calls across keys.
    ESTIMATED_WEIGHT = 500.0
    now = None

    for attempt in range(max_attempts):
        call_started = __import__("time").perf_counter()
        now = __import__("time").time()
        entry = pool.best_key(ESTIMATED_WEIGHT, now)
        if entry is None:
            return None
        client = entry.client
        try:
            # Reserve before the network call so concurrent scene alignments
            # spread across keys instead of all selecting the same idle key.
            pool.record(entry, ESTIMATED_WEIGHT, now)
            with open(wav_path, "rb") as f:
                resp = client.audio.transcriptions.create(
                    model=WHISPER_MODEL,
                    file=f,
                    language="en",
                    response_format="verbose_json",
                    timestamp_granularities=["word", "segment"],
                    timeout=max(
                        3.0,
                        float(os.environ.get(
                            "WORD_TIMESTAMPS_REQUEST_TIMEOUT_SECONDS", "8"
                        )),
                    ),
                )
            words = _extract_transcription_words(resp)
            if not words:
                raise RuntimeError(
                    "Whisper returned no word timestamps in top-level or segment data."
                )
            if job_id:
                try:
                    from run_log import log_llm_call
                    log_llm_call(
                        job_id=job_id,
                        stage="whisper_words",
                        provider="groq",
                        model=WHISPER_MODEL,
                        key_prefix=entry.key[:10],
                        prompt_tokens=0,
                        completion_tokens=0,
                        latency_ms=(__import__("time").perf_counter() - call_started) * 1000,
                        status="ok",
                        response_id=getattr(resp, "id", None),
                        audio_seconds=audio_duration_seconds(wav_path),
                        transcribed_words=len(words),
                        usage_source="audio_duration_billing",
                    )
                except Exception:
                    pass
            return words
        except Exception as exc:
            last_error = str(exc)
            # 429 / rate-limit → quarantine the key, try the next one.
            if any(tok in str(exc) for tok in ("429", "rate_limit", "quota")):
                pool.quarantine(entry, now, severity="minute")
            continue

    if job_id and last_error:
        try:
            from run_log import log_llm_call
            log_llm_call(
                job_id=job_id,
                stage="whisper_words",
                provider="groq",
                model=WHISPER_MODEL,
                key_prefix=entries[0].key[:10],
                prompt_tokens=0,
                completion_tokens=0,
                latency_ms=0.0,
                status="error",
                error=last_error[:200],
            )
        except Exception:
            pass
    return None


def save_word_timestamps(wav_path: Path, words: Optional[List[Dict[str, Any]]]) -> Optional[Path]:
    """Persist word timestamps next to the narration WAV as words.json."""
    if not words:
        return None
    out = Path(wav_path).with_name("words.json")
    try:
        out.write_text(
            json.dumps(words, ensure_ascii=False, indent=1) + "\n",
            encoding="utf-8",
        )
        return out
    except OSError:
        return None


def load_word_timestamps(scene_dir) -> Optional[List[Dict[str, Any]]]:
    """Load a previously persisted words.json, if present."""
    import json as _json
    p = Path(scene_dir) / "words.json"
    if not p.is_file():
        return None
    try:
        return _json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
